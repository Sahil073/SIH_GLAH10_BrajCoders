export type TranslationKey = keyof typeof TRANSLATIONS.en;

const STORAGE_KEY = "sanjeevni_app_language";

// Global listener pattern for instant multi-screen reactive language updates
let currentLang: LanguageCode = "en";
const listeners = new Set<(lang: LanguageCode) => void>();

export async function getSavedLanguage(): Promise<LanguageCode> {
  try {
    if (Platform.OS === "web") {
      const saved = typeof window !== "undefined" ? window.localStorage?.getItem(STORAGE_KEY) : null;
      if (saved && (["en", "hi", "bn", "mr", "te", "ta"] as string[]).includes(saved)) {
        return saved as LanguageCode;
      }
    } else {
      const saved = await SecureStore.getItemAsync(STORAGE_KEY);
      if (saved && (["en", "hi", "bn", "mr", "te", "ta"] as string[]).includes(saved)) {
        return saved as LanguageCode;
      }
    }
  } catch (e) {
    console.warn("[i18n] Error reading saved language:", e);
  }
  return "en";
}

export async function setSavedLanguage(lang: LanguageCode): Promise<void> {
  currentLang = lang;
  listeners.forEach((cb) => cb(lang));

  try {
    if (Platform.OS === "web") {
      if (typeof window !== "undefined") {
        window.localStorage?.setItem(STORAGE_KEY, lang);
      }
    } else {
      await SecureStore.setItemAsync(STORAGE_KEY, lang);
    }
  } catch (e) {
    console.warn("[i18n] Error saving language:", e);
  }
}

/**
 * Reactive hook that listens to language changes and provides translations
 */
export function useLanguage() {
  const [lang, setLang] = useState<LanguageCode>(currentLang);

  useEffect(() => {
    // Hydrate from storage on mount
    void getSavedLanguage().then((saved) => {
      setLang(saved);
      currentLang = saved;
    });

    const handler = (newLang: LanguageCode) => {
      setLang(newLang);
    };
    listeners.add(handler);
    return () => {
      listeners.delete(handler);
    };
  }, []);

  const changeLanguage = useCallback(async (newLang: LanguageCode) => {
    await setSavedLanguage(newLang);
    setLang(newLang);
  }, []);

  const t = useCallback(
    (key: TranslationKey): string => {
      const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
      return (dict as any)[key] ?? (TRANSLATIONS.en as any)[key] ?? String(key);
    },
    [lang]
  );

  const currentLanguageInfo =
    SUPPORTED_LANGUAGES.find((l) => l.code === lang) || SUPPORTED_LANGUAGES[0];

  return {
    language: lang,
    languages: SUPPORTED_LANGUAGES,
    currentLanguageInfo,
    changeLanguage,
    t,
  };
}
